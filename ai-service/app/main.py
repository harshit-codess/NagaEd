import logging

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse

from .groq_client import GroqNotConfigured, GroqUpstreamError, suggest_usernames
from .schemas import ErrorResponse, SuggestRequest, SuggestResponse

logger = logging.getLogger("ai-service")
logging.basicConfig(level=logging.INFO)

app = FastAPI(
    title="NagaEd AI Microservice",
    version="1.0.0",
    description=(
        "Small AI helper service used by the registration flow. "
        "`POST /api/suggest-username` asks an LLM (via the **Groq API**) for three creative, "
        "unique usernames based on a list of interests."
    ),
)


def error_response(status: int, code: str, message: str, details: list | None = None) -> JSONResponse:
    body: dict = {"error": {"code": code, "message": message}}
    if details:
        body["error"]["details"] = details
    return JSONResponse(status_code=status, content=body)


@app.exception_handler(RequestValidationError)
async def validation_handler(request: Request, exc: RequestValidationError):
    """Malformed input -> 422 in the same error shape as the Node API."""
    details = [
        {"field": ".".join(str(p) for p in e["loc"] if p != "body"), "message": e["msg"]}
        for e in exc.errors()
    ]
    return error_response(422, "VALIDATION_ERROR", "Validation failed", details)


@app.get("/health", tags=["meta"], summary="Liveness probe")
async def health() -> dict:
    return {"status": "ok"}


@app.post(
    "/api/suggest-username",
    response_model=SuggestResponse,
    tags=["ai"],
    summary="Suggest three creative usernames from interests",
    description=(
        "Send 1-10 interests and receive exactly three unique username suggestions generated by an LLM."
    ),
    responses={
        422: {"model": ErrorResponse, "description": "Malformed or invalid request body"},
        502: {"model": ErrorResponse, "description": "Groq API call failed or returned unusable output"},
        503: {"model": ErrorResponse, "description": "GROQ_API_KEY is not configured"},
        504: {"model": ErrorResponse, "description": "Groq API timed out"},
    },
)
async def suggest_username(body: SuggestRequest):
    try:
        names = await suggest_usernames(body.interests)
    except GroqNotConfigured:
        logger.error("GROQ_API_KEY is not set")
        return error_response(503, "AI_NOT_CONFIGURED", "AI service is not configured")
    except GroqUpstreamError as exc:
        logger.warning("Groq failure: %s", exc)
        if exc.timeout:
            return error_response(504, "AI_TIMEOUT", "The AI provider timed out, please try again")
        return error_response(502, "AI_UPSTREAM_ERROR", "Could not generate suggestions right now")
    return SuggestResponse(suggestions=names)
